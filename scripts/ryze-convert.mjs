import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
process.chdir(root);
const source = 'blog/data';
const marker = '<!-- Generated by Ryze publishing; do not edit directly. -->';
const esc = s => String(s ?? '').replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const read = p => fs.readFile(p, 'utf8');
const exists = async p => { try { await fs.access(p); return true; } catch { return false; } };
const write = async (p, text) => { if (await exists(p) && await read(p) === text) return; await fs.mkdir(path.dirname(p), {recursive:true}); await fs.writeFile(p, text); };
const jsonld = data => JSON.stringify(data).replace(/</g, '\\u003c');
const template = await read('blog-local-seo-2026.html');
if (!template.includes('<section class="post-hero">') || !template.includes('<article class="article-content">')) throw Error('Article template changed; review required');
let posts = JSON.parse(await read('_data/posts.json'));
const files = (await exists(source)) ? (await fs.readdir(source)).filter(f => f.endsWith('.json')).sort() : [];
const articles = [];
for (const file of files) {
  const a = JSON.parse(await read(path.join(source, file)));
  if (a.status !== 'published') continue;
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(a.slug ?? '') || !a.title || !a.body_html?.trim()) throw Error('Invalid article: ' + file);
  const out = `blog/${a.slug}/index.html`;
  const old = posts.find(p => p.slug === a.slug);
  if (old && !old.ryze) throw Error('Existing non-Ryze article uses slug: ' + a.slug);
  if (await exists(out) && !(await read(out)).includes(marker)) throw Error('Refusing to overwrite non-Ryze page: ' + out);
  if (!/^\d{4}-\d{2}-\d{2}/.test(a.published_at ?? '') || !Number.isFinite(Date.parse(a.published_at))) throw Error('Invalid publication date: ' + file);
  articles.push({a, out});
}
let catalogChanged = false;
for (const {a, out} of articles) {
  const test = a.slug === 'ryze-setup-test';
  const url = `https://nsyght.com/blog/${a.slug}`;
  const date = a.published_at.slice(0,10);
  const modified = a.updated_at || a.published_at;
  const category = /chatgpt|perplexity|generative|\bgeo\b|\baeo\b|ai search/i.test(a.primary_keyword || a.title) ? 'AI Search' : 'Local SEO';
  const minutes = Math.max(1, Math.ceil(a.body_html.replace(/<[^>]*>/g,' ').split(/\s+/).length/220));
  let image = '';
  if (a.image?.url) {
    const remote = new URL(a.image.url);
    if (!['https:', 'http:'].includes(remote.protocol)) throw Error('Invalid image protocol');
    const response = await fetch(remote, {signal:AbortSignal.timeout(45000)});
    if (!response.ok) throw Error('Image download failed: ' + response.status);
    const mime = (response.headers.get('content-type') || '').split(';')[0];
    const ext = {'image/jpeg':'jpg','image/png':'png','image/webp':'webp','image/avif':'avif','image/gif':'gif'}[mime];
    if (!ext) throw Error('Unsupported image content type: ' + mime);
    const bytes = Buffer.from(await response.arrayBuffer());
    if (bytes.length > 15000000) throw Error('Image exceeds 15 MB');
    const hash = createHash('sha256').update(bytes).digest('hex').slice(0,12);
    image = `/images/blog/ryze-${a.slug}-${hash}.${ext}`;
    await fs.mkdir('images/blog', {recursive:true});
    if (!(await exists('.' + image))) await fs.writeFile('.' + image, bytes);
  }
  const meta = a.meta_description || a.excerpt || '';
  const schema = {'@context':'https://schema.org','@type':'Article',headline:a.title,description:meta,datePublished:date,dateModified:modified,articleSection:category,keywords:a.primary_keyword || '',mainEntityOfPage:url,author:{'@type':'Person',name:'Don Phelps',url:'https://nsyght.com/about'},publisher:{'@type':'Organization',name:'NSYGHT',url:'https://nsyght.com'},...(image ? {image:'https://nsyght.com'+image} : {})};
  let doc = template.replace(/<title>[\s\S]*?<\/title>/, `<title>${esc(a.meta_title || a.title + ' - NSYGHT')}</title>`);
  doc = doc.replace(/<meta\s+(?:name="description"|property="og:[^"]+")[^>]*>/g,'').replace(/<link\s+rel="canonical"[^>]*>/g,'').replace(/<script type="application\/ld\+json">[\s\S]*?<\/script>/g,'');
  const head = `<meta name="description" content="${esc(meta)}"/>\n<link rel="canonical" href="${url}"/>\n<meta property="og:title" content="${esc(a.title)}"/>\n<meta property="og:description" content="${esc(meta)}"/>\n<meta property="og:type" content="article"/>\n<meta property="og:url" content="${url}"/>\n${image ? `<meta property="og:image" content="https://nsyght.com${image}"/>` : ''}\n${test ? '<meta name="robots" content="noindex,nofollow"/>' : ''}\n<script type="application/ld+json">${jsonld(schema)}</script>\n<style>.article-content img{max-width:100%;height:auto}.article-content table{display:block;max-width:100%;overflow-x:auto}.article-content pre{overflow-x:auto}.article-content{overflow-wrap:anywhere}.post-hero .breadcrumb{position:static;height:auto;padding:0;background:transparent;justify-content:flex-start;z-index:auto}</style>`;
  doc = doc.replace('</head>', head + '\n</head>');
  const human = new Date(date+'T12:00:00Z').toLocaleDateString('en-US',{year:'numeric',month:'long',day:'numeric',timeZone:'UTC'});
  const hero = `<section class="post-hero"><div class="post-hero-inner"><nav class="breadcrumb" aria-label="Breadcrumb"><a href="/">Home</a> / <a href="/blog">Resources</a> / ${esc(category)}</nav><div class="post-category">${esc(category)}</div><h1>${esc(a.title)}</h1><div class="post-meta"><div class="post-meta-author"><div><div class="post-meta-name">Don Phelps</div><div class="post-meta-title">The SEO Guru, Founder of NSYGHT</div></div></div><div class="post-meta-info"><span>${human}</span><span>${minutes} min read</span></div></div></div></section>`;
  doc = doc.replace(/<section class="post-hero">[\s\S]*?<\/section>/, () => hero);
  const cover = image ? `<img src="${image}" alt="${esc(a.image.alt || a.title)}" width="1200" height="675" fetchpriority="high"/>` : '';
  doc = doc.replace(/<article class="article-content">[\s\S]*?<\/article>/, () => `<article class="article-content">${marker}\n${cover}\n${a.body_html}\n</article>`);
  doc = doc.replace('</body>', `<script>(function(){const list=document.getElementById('toc-list');if(!list)return;document.querySelectorAll('.article-content h2').forEach(function(h,i){if(!h.id)h.id='section-'+(i+1);const li=document.createElement('li');const link=document.createElement('a');link.href='#'+h.id;link.textContent=h.textContent;li.appendChild(link);list.appendChild(li);});})();</script>\n</body>`);
  if (doc.includes('[object Object]')) throw Error('Invalid object rendered in article');
  await write(out, doc);
  if (!test) {
    const entry = {slug:a.slug,url:'/blog/'+a.slug,file:out,title:a.title,category,excerpt:a.excerpt || meta,read_min:minutes,date,...(image ? {image} : {}),auto:true,ryze:true};
    const index = posts.findIndex(p => p.slug === a.slug);
    if (index === -1) posts.push(entry); else posts[index] = entry;
    catalogChanged = true;
  }
  console.log('Rendered ' + out);
}
if (catalogChanged) {
  await write('_data/posts.json', JSON.stringify(posts,null,2)+'\n');
  // Reuse the site's existing index/hub/feed builders without changing old articles.
  execFileSync('python3',['-c',`import sys\nsys.path.insert(0,'scripts')\nimport build_blog as b\nposts=b.load_posts()\ncats={}\nfor p in posts: cats.setdefault(p['category'],[]).append(p)\nshell=b.read('blog.html')\nb.write('blog.html',b.build_index(shell,posts,cats))\nfor name,ps in cats.items(): b.write('blog-category-'+b.cat_slug(name)+'.html',b.build_hub(shell,name,ps,cats))\nb.write('feed.xml',b.build_feed(posts))`],{stdio:'inherit'});
  let sitemap = await read('sitemap.xml');
  const own = articles.filter(x => x.a.slug !== 'ryze-setup-test');
  for (const {a} of own) {
    const loc = 'https://nsyght.com/blog/'+a.slug;
    if (!sitemap.includes('<loc>'+loc+'</loc>')) sitemap = sitemap.replace('</urlset>', `  <url><loc>${loc}</loc><lastmod>${a.updated_at?.slice(0,10) || a.published_at.slice(0,10)}</lastmod></url>\n</urlset>`);
  }
  await write('sitemap.xml',sitemap);
}
